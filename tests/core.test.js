test('signed session tampering, future time, recovery and retention', () => {
  configure(); const session = makeSession('TUTOR_TEST', 100000000);
  assert.equal(verifySession(session.token, 100000000).id, session.id);
  assert.throws(() => verifySession(`${session.token}x`, 100000000));
  assert.throws(() => verifySession(session.token, 1));
  assert.equal(verifySession(session.token, 100000000 + 3600001).id, session.id);
  assert.throws(() => verifySession(session.token, 100000000 + RETENTION * 1000 + 1));
});
