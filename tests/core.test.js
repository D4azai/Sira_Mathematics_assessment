test('scoring, omissions, level breakdown and recommendations preserve secure arithmetic', () => {
  const answers = QUESTIONS.map(q => q.topic === 'Numerical fluency' ? q.correct : null);
  const score = scoreAttempt(answers, empty());
  assert.equal(score.correct, 9); assert.equal(score.answered, 9); assert.equal(score.unanswered.length, 51);
  assert.equal(score.breakdown[0].category, 'Secure');
  assert.ok(score.plan.every(x => x.topic !== 'Numerical fluency'));
  assert.equal(score.breakdown.reduce((n, x) => n + x.total, 0), 60);
  assert.equal(scoreAttempt(empty(), empty()).correct, 0);
  assert.equal(scoreAttempt(QUESTIONS.map(q => q.correct), empty()).correct, 60);
});
