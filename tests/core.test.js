test('email failure retries identical content and duplicate submission returns stored acceptance', async t => {
  configure(); const double = serviceDouble(); t.mock.method(globalThis, 'fetch', double.fetch);
  const session = makeSession('TUTOR_TEST'); await createAttempt(session);
  const payload = { token: session.token, answers: QUESTIONS.map(q => q.correct), confidence: empty(), revision: 0 };
  double.setEmail(500, null);
  assert.equal((await invoke(submit, payload)).status, 502);
  assert.equal((await getAttempt(session.id)).result, undefined);
  double.setEmail(200, null); assert.equal((await invoke(submit, payload)).status, 502);
  double.setEmail(200); const accepted = await invoke(submit, payload);
  assert.equal(accepted.status, 200); assert.equal(accepted.data.score, 60);
  const count = double.sends.length;
  assert.deepEqual((await invoke(submit, payload)).data, accepted.data); assert.equal(double.sends.length, count);
  assert.deepEqual(double.sends[0], double.sends[2]);
  assert.deepEqual(double.sends[0].body.to, ['aymane.chellak@outlook.fr']);
});
